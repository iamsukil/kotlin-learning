fun main() {

    val a = 20
    val b = 10

    println(a + b)
    println(a - b)
    println(a * b)
    println(a / b)
    println(a % b)

    println(a > b)
    println(a < b)
    println(a == b)
    println(a != b)

    val age = 23
    val hasId = true

    println(age >= 18 && hasId)
    println(age < 18 || hasId)
    println(!hasId)
}